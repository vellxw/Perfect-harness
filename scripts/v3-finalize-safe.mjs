import fs from 'node:fs';
import assert from 'node:assert/strict';
const path='scripts/v3-finalize.mjs';let script=fs.readFileSync(path,'utf8');
const anchor="old.replaceAll('0.2.1','0.3.0')";
assert.ok(script.includes(anchor),'Ancla de versión no encontrada');
script=script.replace(anchor,String.raw`old.replace(/(?<![\d.])0\.2\.1(?!\d)/g,'0.3.0')`);
const security=fs.readFileSync('tests/security/evidence.test.ts','utf8');
fs.writeFileSync('scripts/.v3-finalize-safe-runtime.mjs',script);
await import('./.v3-finalize-safe-runtime.mjs');
assert.equal(fs.readFileSync('tests/security/evidence.test.ts','utf8'),security,'La actualización de versión no debe modificar direcciones IP ni las pruebas de seguridad');
